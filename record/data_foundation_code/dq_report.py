"""(d) Data-quality report on the v2 panel + old-vs-new coverage table.  python3 -I code/dq_report.py
Writes out/dq_by_year.csv, out/coverage_old_vs_new.csv, out/DATA_QUALITY.md."""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np, pandas as pd
from common import *
import calendar_fix as CF


def gap_table(pan, sessions):
    """Missing sessions inside each entity's life (between consecutive rows), on the XASX calendar.
    Market-wide missing sessions (no rows for anyone) are counted separately."""
    pos = pd.Series(np.arange(len(sessions)), index=sessions)
    p = pan[['eid', 'date']].copy()
    p['i'] = p.date.map(pos)
    p = p.dropna(subset=['i'])
    p['gap'] = p.groupby('eid').i.diff() - 1
    g = p[p.gap > 0]
    return g


def main():
    pan = pd.read_pickle(os.path.join(OUT, 'panel_v2_long.pkl'))
    cal = pd.read_csv(os.path.join(OUT, 'calendar_dates.csv'), parse_dates=['date'], index_col='date')
    ses = CF.xasx_sessions(CAL_START, CAL_END)
    ses = ses[(ses >= pan.date.min()) & (ses <= pan.date.max())]
    miss = pd.read_csv(os.path.join(OUT, 'calendar_missing_sessions.csv'), parse_dates=['date'])
    ses_data = ses[~ses.isin(miss.date)]
    g = gap_table(pan, ses_data)
    y = pan.date.dt.year
    t = pd.DataFrame({'rows': pan.groupby(y).size(), 'entities': pan.groupby(y).eid.nunique()})
    gy = g.date.dt.year
    t['gap_episodes'] = g.groupby(gy).size()
    t['gap_missing_sessions'] = g.groupby(gy).gap.sum()
    t['gap_episodes_ge_20_sessions'] = g[g.gap >= 20].groupby(gy).size()
    t['marketwide_missing_sessions'] = miss.groupby(miss.date.dt.year).size()
    for f in ['zero_vol', 'zero_vol_close_flat', 'zero_vol_close_moved', 'copy_row', 'copy_day', 'bad_tick', 'spike_residual', 'split_residual', 'big_move_unexplained', 'link_day']:
        t[f] = pan[pan[f].fillna(False).astype(bool)].groupby(y).size()
    rem = cal[cal.removed]
    t['calendar_dates_removed'] = rem.groupby(rem.index.year).size()
    t['calendar_rows_removed_raw_all_codes'] = rem.groupby(rem.index.year).raw_rows.sum()
    runs = pd.read_csv(os.path.join(OUT, 'index_ffill_runs.csv'), parse_dates=['start', 'end'])
    ix = pd.read_pickle(os.path.join(OUT, 'index_v2.pkl'))
    t['xjo_ffill_days'] = ix[ix.xjo_ffill].groupby(ix[ix.xjo_ffill].index.year).size()
    t['xtr_ffill_days'] = ix[ix.xtr_ffill].groupby(ix[ix.xtr_ffill].index.year).size()
    t = t.fillna(0).astype(int)
    t.index.name = 'year'
    t.to_csv(os.path.join(OUT, 'dq_by_year.csv'))
    # ---- coverage old vs new
    Pold = pd.read_pickle(os.path.join(CS_DATA, 'P.pkl'))
    Cold = pd.read_pickle(os.path.join(NICHE_OUT, 'Craw.pkl'))
    Pn = pd.read_pickle(os.path.join(OUT, 'P_v2.pkl'))
    Cn = pd.read_pickle(os.path.join(OUT, 'Craw_v2.pkl'))
    yo, yn = Pold.index.year, Pn.index.year
    cov = pd.DataFrame({
        'old_dates': Pold.groupby(yo).size(),
        'new_dates': Pn.groupby(yn).size(),
        'old_entities': Pold.notna().groupby(yo).any().sum(axis=1),
        'new_entities': Pn.notna().groupby(yn).any().sum(axis=1),
        'old_adjusted_company_days': Pold.notna().groupby(yo).sum().sum(axis=1),
        'new_adjusted_company_days': Pn.notna().groupby(yn).sum().sum(axis=1),
    })
    Pd1 = Pold.loc[:D1_END]; Cd1 = Cold.reindex(index=Pd1.index, columns=Pd1.columns)
    cov['old_raw_close_missing_where_adjusted_exists(niche files)'] = (Pd1.notna() & Cd1.isna()).groupby(Pd1.index.year).sum().sum(axis=1)
    Pn1 = Pn.loc[:D1_END]; Cn1 = Cn.reindex(index=Pn1.index, columns=Pn1.columns)
    cov['new_raw_close_missing_where_adjusted_exists'] = (Pn1.notna() & Cn1.isna()).groupby(Pn1.index.year).sum().sum(axis=1)
    cov = cov.fillna(0).astype(int); cov.index.name = 'year'
    cov.to_csv(os.path.join(OUT, 'coverage_old_vs_new.csv'))
    # defect (a) headline, old basis vs new basis
    old_m = (Pd1.notna() & Cd1.isna())
    per = old_m.sum(); per = per[per > 0]
    new_m = (Pn1.notna() & Cn1.isna()); pern = new_m.sum(); pern = pern[pern > 0]
    S = dict(old_missing_company_days=int(old_m.values.sum()), old_missing_companies=int(len(per)),
             old_missing_companies_gt20=int((per > 20).sum()),
             new_missing_company_days=int(new_m.values.sum()), new_missing_companies=int(len(pern)),
             new_missing_reason=pan[(pan.src == 'D1') & pan.c.isna()].shape[0])
    save_json(dict(summary=S, gap_length_hist={str(k): int(v) for k, v in pd.cut(g.gap, [0, 1, 2, 5, 20, 60, 1e9]).value_counts().sort_index().items()}),
              os.path.join(OUT, 'dq_summary.json'))
    with open(os.path.join(OUT, 'DATA_QUALITY.md'), 'w') as f:
        f.write('# Data-quality report, v2 panel\n\nGenerated by code/dq_report.py on ' + now_utc() + '.\n\n')
        f.write('Flags never delete rows (only the calendar fix deletes). Definitions in README.md.\n\n')
        f.write('## Counts by year\n\n' + md_table(t.reset_index(), '{:,.0f}') + '\n\n')
        f.write('## Coverage, old (company_study P.pkl + niche raw files) vs new (v2)\n\n' + md_table(cov.reset_index(), '{:,.0f}') + '\n\n')
        f.write('## Rename defect headline\n\n```\n' + json.dumps(S, indent=1) + '\n```\n')
    print(json.dumps(S)); print(t.sum().to_dict())


if __name__ == '__main__':
    main()
